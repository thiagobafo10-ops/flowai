import { test, expect } from "@playwright/test";
import { newEmail, signUpWithOrg } from "./support/auth";
import { clearRateLimits, psql } from "./support/local-db";
import { confirmWebhook, connectionFor, runInstagramWorker, sendInstagramComment, connectInstagram, INSTAGRAM_TEST_URL } from "./support/instagram";
test.beforeEach(() => clearRateLimits());
test("VIP: salvar prévia, verificar, ativar, responder sem duplicar e pausar", async ({ page }, testInfo) => {
 const email = newEmail(); await signUpWithOrg(page, email, "VIP E2E"); await connectInstagram(page); await confirmWebhook(email); await page.reload();
 const card = page.getByTestId("instagram-vip");
 await expect(card.getByRole("button", { name: "Ativar VIP", exact: true })).toBeDisabled();
 await expect(card).toContainText("Aqui está o convite para o nosso grupo VIP do WhatsApp: https://chat.whatsapp.com/FFHuLdtAehRCoIDP67bX5r");
 await card.getByRole("button", { name: "Salvar desativado" }).click();
 await expect(card.getByRole("status")).toContainText("salva desativada");
 const c = connectionFor(email);
 expect(psql(`select enabled from public.instagram_vip_settings where channel_id='${c.channelId}'`)).toBe("f");
 expect(psql(`select count(*) from public.instagram_vip_intents where channel_id='${c.channelId}'`)).toBe("0");
 await card.getByLabel("Link do grupo WhatsApp").fill("https://chat.whatsapp.com/CustomDraftGroup");
 await card.getByLabel("Resposta pública VIP").fill("Resposta personalizada ainda não salva");
 await card.getByRole("button", { name: "Verificar permissão de comentários" }).click();
 await expect(card.getByRole("button", { name: "Ativar VIP", exact: true })).toBeEnabled();
 await expect(card.getByLabel("Link do grupo WhatsApp")).toHaveValue("https://chat.whatsapp.com/CustomDraftGroup");
 await expect(card.getByLabel("Resposta pública VIP")).toHaveValue("Resposta personalizada ainda não salva");
 await card.getByLabel("Link do grupo WhatsApp").fill("https://chat.whatsapp.com/FFHuLdtAehRCoIDP67bX5r");
 await card.getByLabel("Resposta pública VIP").fill("Quer entrar no nosso grupo VIP do WhatsApp? Comente VIP para receber o link no Direct.");
 await card.getByRole("button", { name: "Ativar VIP", exact: true }).click();
 await expect(card.getByText("VIP ativo", { exact: true })).toBeVisible();
 expect(psql(`select enabled from public.instagram_vip_settings where channel_id='${c.channelId}'`)).toBe("t");
 const activatedAt = Date.parse(psql(`select activated_at from public.instagram_vip_settings where channel_id='${c.channelId}'`));
 await expect.poll(() => Date.now() > activatedAt + 1100).toBe(true);
 const plain = String(Date.now()) + "1"; const vip = String(Date.now()) + "2";
 await sendInstagramComment(email, plain, "Gostei"); await runInstagramWorker();
 expect(psql(`select count(*) from public.instagram_vip_intents where channel_id='${c.channelId}' and comment_id='${plain}' and kind='public' and state='sent'`)).toBe("1");
 expect(psql(`select count(*) from public.instagram_vip_intents where channel_id='${c.channelId}' and comment_id='${plain}' and kind='private' and state='sent'`)).toBe("0");
 await sendInstagramComment(email, vip, "Quero VIP!"); await runInstagramWorker();
 expect(psql(`select count(*) from public.instagram_vip_intents where channel_id='${c.channelId}' and comment_id='${vip}' and state='sent'`)).toBe("2");
 await sendInstagramComment(email, vip, "Quero VIP!"); await runInstagramWorker();
 const calls = await (await fetch(`${INSTAGRAM_TEST_URL}/__test__/graph-calls`)).json();
 expect(calls.filter((call: { accountId: string; body: { publicCommentId?: string } }) => call.accountId === c.accountId && call.body.publicCommentId === vip)).toHaveLength(1);
 expect(calls.filter((call: { accountId: string; body: { recipient?: { comment_id?: string } } }) => call.accountId === c.accountId && call.body.recipient?.comment_id === vip)).toHaveLength(1);
 await card.getByLabel("Link do grupo WhatsApp").fill("https://invalid.test/");
 await card.getByRole("button", { name: "Pausar VIP" }).click();
 await expect(card.getByText("VIP desativado", { exact: true })).toBeVisible();
 const paused = String(Date.now()) + "3"; await sendInstagramComment(email, paused, "VIP"); await runInstagramWorker();
 expect(psql(`select count(*) from public.instagram_vip_intents where channel_id='${c.channelId}' and comment_id='${paused}' and state='sent'`)).toBe("0");
 await card.screenshot({ path: testInfo.outputPath("vip-config.png") });
});
